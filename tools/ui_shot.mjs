import { chromium } from "playwright-core";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium" });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on("pageerror", e => errors.push("pageerror: " + e.message));
page.on("response", r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
await page.goto("http://127.0.0.1:8765/index.html");
await page.waitForSelector("#click-to-start:not(.hidden)");
await page.click("#click-to-start");
await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/u_title.png` });
await page.click("#btn-new"); await page.click("#name-ok");
await page.evaluate(() => setInterval(() => { const b = document.querySelector("#choices button"); if (b) b.click(); else __sh.advance(); }, 20));
await page.waitForFunction(() => __sh.story && __sh.v.act >= 1 && !__sh.busy, null, { timeout: 60000 });
await page.evaluate(() => __sh.setScene("street"));
await page.waitForTimeout(500);
await page.mouse.move(1000, 400);
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/u_hover.png` });
await page.keyboard.press("m"); await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/u_map.png` });
await page.keyboard.press("Escape");
await page.keyboard.press("j"); await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/u_journal.png` });
await page.click('.tabs button[data-tab="noticed"]'); await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/u_journal2.png` });
console.log(errors.join("\n") || "no errors");
await browser.close();
